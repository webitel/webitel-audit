-- +goose Up
-- Scorecards (audit forms) moved from call_center.cc_audit_form: criteria, groups and
-- options are rows with ids and position instead of the questions jsonb.

CREATE TABLE audit.scorecard (
    id               int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- BY DEFAULT: Jira DT-41 (engine -> audit migration script) copies the engine ids
    domain_id        bigint NOT NULL REFERENCES directory.wbt_domain (dc) ON DELETE CASCADE,
    name             varchar(256) NOT NULL,
    description      varchar(516) NULL,
    enabled          boolean NOT NULL DEFAULT false,
    archive          boolean NOT NULL DEFAULT false,
    editable         boolean NOT NULL DEFAULT true,
    -- 1=call, 2=chat, 3=email
    interaction_type smallint[] NOT NULL
        CONSTRAINT scorecard_interaction_type_check
            CHECK (cardinality(interaction_type) >= 1 AND interaction_type <@ '{1,2,3}'::smallint[]),
    created_at       timestamptz NOT NULL DEFAULT now(),
    created_by       bigint NOT NULL,
    updated_at       timestamptz NOT NULL DEFAULT now(),
    updated_by       bigint NULL,
    CONSTRAINT scorecard_domain_name_key UNIQUE (domain_id, name),
    CONSTRAINT scorecard_id_domain_key UNIQUE (id, domain_id)  -- target of scorecard_acl (object, dc)
);
CREATE INDEX scorecard_domain_created_idx ON audit.scorecard (domain_id, created_at DESC);

-- Same shape and indexes as call_center.cc_audit_form_acl.
CREATE TABLE audit.scorecard_acl (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dc      bigint NOT NULL REFERENCES directory.wbt_domain (dc) ON DELETE CASCADE,
    grantor bigint NULL REFERENCES directory.wbt_auth (id) ON DELETE SET NULL,
    object  int NOT NULL,
    subject bigint NOT NULL,
    access  smallint NOT NULL DEFAULT 0,
    CONSTRAINT scorecard_acl_object_fk FOREIGN KEY (object, dc)
        REFERENCES audit.scorecard (id, domain_id) ON DELETE CASCADE,
    CONSTRAINT scorecard_acl_subject_fk FOREIGN KEY (subject, dc)
        REFERENCES directory.wbt_auth (id, dc) ON DELETE CASCADE
);
CREATE INDEX scorecard_acl_grantor_idx ON audit.scorecard_acl (grantor);
CREATE UNIQUE INDEX scorecard_acl_object_subject_udx ON audit.scorecard_acl (object, subject) INCLUDE (access);
CREATE UNIQUE INDEX scorecard_acl_subject_object_udx ON audit.scorecard_acl (subject, object) INCLUDE (access);

-- Copy of call_center.tg_obj_default_rbac: grants the creator full access and copies the
-- role defaults of the object class. It writes to <trigger table>_acl, so the ACL table of
-- audit.scorecard must be named audit.scorecard_acl.
-- +goose StatementBegin
CREATE FUNCTION audit.tg_obj_default_rbac() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    AS $_$
BEGIN

        EXECUTE format(
'INSERT INTO %I.%I AS acl (dc, object, grantor, subject, access)
 SELECT $1, $2, rbac.grantor, rbac.subject, rbac.access
   FROM (
    -- NEW object OWNER access SUPER(255) mode (!)
    SELECT $3, $3, (255)::int2
     UNION ALL
    SELECT DISTINCT ON (rbac.subject)
      -- [WHO] grants MAX of WINDOW subset access level
        first_value(rbac.grantor) OVER sub
      -- [WHOM] role/user administrative unit
      , rbac.subject
      -- [GRANT] ALL of WINDOW subset access mode(s)
      , bit_or(rbac.access) OVER sub

      FROM directory.wbt_default_acl AS rbac
      JOIN directory.wbt_class AS oc ON (oc.dc, oc.name) = ($1, %L)
     WHERE rbac.object = oc.id
       AND rbac.subject <> $3
        -- EXISTS( OWNER membership WITH grantor user/role )
       AND (rbac.grantor = $3 OR EXISTS(SELECT true
             FROM directory.wbt_auth_member sup
            WHERE sup.member_id = $3
              AND sup.role_id = rbac.grantor
           ))
    WINDOW sub AS (PARTITION BY rbac.subject ORDER BY rbac.access DESC)

   ) AS rbac(grantor, subject, access)',
            tg_table_schema,
            tg_table_name||'_acl',
            tg_argv[0]::name -- objclass: directory.wbt_class.name
        )
    --      :srv,   :oid,   :rid
    USING NEW.domain_id, NEW.id, NEW.created_by;
    -- FOR EACH ROW
    RETURN NEW;

END
$_$;
-- +goose StatementEnd

-- Fix of the engine trigger: call_center passed 'cc_audit_form_acl', which is not a
-- directory.wbt_class name, so role default access was never copied to new forms.
-- The class of audit forms is 'cc_audit_form' (engine model.PermissionAuditFrom).
CREATE TRIGGER scorecard_set_rbac_acl AFTER INSERT ON audit.scorecard
    FOR EACH ROW EXECUTE FUNCTION audit.tg_obj_default_rbac('cc_audit_form');

CREATE TABLE audit.scorecard_team (
    scorecard_id int NOT NULL REFERENCES audit.scorecard (id) ON DELETE CASCADE,
    team_id      bigint NOT NULL,
    domain_id    bigint NOT NULL,
    PRIMARY KEY (scorecard_id, team_id)
);
CREATE INDEX scorecard_team_domain_team_idx ON audit.scorecard_team (domain_id, team_id);

CREATE TABLE audit.scorecard_criteria_group (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    scorecard_id int NOT NULL REFERENCES audit.scorecard (id) ON DELETE CASCADE,
    name         varchar(256) NOT NULL,
    position     smallint NOT NULL
);
-- Deferred: the rows of one save are written one by one, so a group may take the name another group of the same save
-- gives up (a swap, or a rename plus a new group with the old name); it is checked when the transaction commits.
ALTER TABLE audit.scorecard_criteria_group
    ADD CONSTRAINT scorecard_criteria_group_name_udx UNIQUE (scorecard_id, name) DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE audit.scorecard_criterion (
    id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    scorecard_id       int NOT NULL REFERENCES audit.scorecard (id) ON DELETE CASCADE,
    group_id           uuid NULL REFERENCES audit.scorecard_criteria_group (id) ON DELETE SET NULL,
    position           smallint NOT NULL,
    -- 1=score, 2=option, 3=yes (same numbers as engine AuditQuestionType)
    type               smallint NOT NULL CHECK (type IN (1, 2, 3)),
    question           text NOT NULL,
    description        text NULL,
    required           boolean NOT NULL DEFAULT false,
    critical_violation boolean NOT NULL DEFAULT false,
    allow_na           boolean NOT NULL DEFAULT false,
    min_score          smallint NULL,
    max_score          smallint NULL,
    weight             numeric(4, 2) NOT NULL DEFAULT 1 CHECK (weight BETWEEN 1 AND 10),
    require_comment    boolean NOT NULL DEFAULT false,
    comment_threshold  smallint NULL
);
CREATE INDEX scorecard_criterion_scorecard_position_idx ON audit.scorecard_criterion (scorecard_id, position);
-- Deleting a group sets group_id to NULL on its criteria (ON DELETE SET NULL); without it that scans the table.
CREATE INDEX scorecard_criterion_group_idx ON audit.scorecard_criterion (group_id);

CREATE TABLE audit.scorecard_criterion_option (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    criterion_id    uuid NOT NULL REFERENCES audit.scorecard_criterion (id) ON DELETE CASCADE,
    position        smallint NOT NULL,
    name            text NOT NULL,
    -- real because the API score is float. No -15..15 CHECK, see min_score of audit.scorecard_criterion.
    score           real NOT NULL,
    require_comment boolean NOT NULL DEFAULT false
);
CREATE INDEX scorecard_criterion_option_criterion_idx ON audit.scorecard_criterion_option (criterion_id);

-- Immutable copy of the form content an evaluation was made with.
CREATE TABLE audit.scorecard_snapshot (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    scorecard_id int NOT NULL REFERENCES audit.scorecard (id) ON DELETE CASCADE,
    domain_id    bigint NOT NULL,
    hash         bytea NOT NULL,  -- sha256 of content, model.Scorecard.ContentHash
    content      jsonb NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT scorecard_snapshot_hash_key UNIQUE (scorecard_id, hash)
);

